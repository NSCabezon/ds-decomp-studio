"""Blocks of 50 functions of the same difficulty, and the queue of people / AIs working on them.

Stored in the game repo, so everyone who clones it sees the same queue:
  .studio/blocks.json             the blocks (generated by `rebuild`; claimed blocks are kept as they are)
  .studio/claims/<block>.json     who works on a block (one file per claim: two people never edit the same file)
  .studio/finished/<block>.json   claims closed with `done`
A claim nobody touched for CLAIM_HOURS goes back to the queue.
"""
import json
import threading
import time

from . import config, difficulty, games, gitutil

_lock = threading.RLock()
KINDS = {"human": "Humain", "claude": "Claude / IA", "qwen": "Qwen (local)", "auto": "Machine (auto_match)"}


def _dir(g):
    return g.path / config.STUDIO_DIR


def _read(p, default):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return default


def _write(p, obj):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(obj, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def load(g) -> dict:
    return _read(_dir(g) / "blocks.json", {"generation": 0, "blocks": []})


def claims(g) -> dict:
    d = _dir(g) / "claims"
    return {p.stem: _read(p, {}) for p in sorted(d.glob("*.json"))} if d.exists() else {}


def finished(g) -> dict:
    d = _dir(g) / "finished"
    return {p.stem: _read(p, {}) for p in sorted(d.glob("*.json"))} if d.exists() else {}


def expired(c: dict) -> bool:
    return time.time() - c.get("touched", c.get("at", 0)) > config.CLAIM_HOURS * 3600


def rebuild(g, size=config.BLOCK_SIZE, commit=True) -> dict:
    """Recomputes the blocks from the functions left to do. Blocks with a live claim are kept unchanged."""
    with _lock:
        old = load(g)
        live = {k for k, c in claims(g).items() if not expired(c)}
        kept = [b for b in old["blocks"] if b["id"] in live]
        taken = {f for b in kept for f in b["functions"]}
        rated = difficulty.rate_all(g.functions(), games.portable(g))
        gen = old.get("generation", 0) + 1
        blocks = list(kept)
        for lvl in range(6):
            fns = sorted((r for r in rated if r["level"] == lvl and r["name"] not in taken), key=lambda r: r["addr"])
            for k in range(0, len(fns), size):
                chunk = fns[k:k + size]
                blocks.append({"id": f"L{lvl}-{gen:02}{k // size + 1:03}", "level": lvl,
                               "functions": [r["name"] for r in chunk],
                               "bytes": sum(r["size"] for r in chunk),
                               "addr": [chunk[0]["addr"], chunk[-1]["addr"] + chunk[-1]["size"]]})
        data = {"generation": gen, "created": time.time(), "block_size": size, "blocks": blocks}
        _write(_dir(g) / "blocks.json", data)
        if commit:
            gitutil.commit_studio(g.path, f"studio: {len(blocks)} blocks (generation {gen})")
            gitutil.push(g.path)
        return data


def view(g) -> list[dict]:
    """Blocks with their live state: free / claimed / expired / done, and progress."""
    data = load(g)
    if not data["blocks"] and g.ready:
        data = rebuild(g, commit=False)
    rows = {r["name"]: r for r in g.functions()}
    cl, fin = claims(g), finished(g)
    out = []
    for b in data["blocks"]:
        fns = [rows[n] for n in b["functions"] if n in rows]
        left = [r for r in fns if not r["done"]]
        c = cl.get(b["id"])
        if not left:
            state = "done"
        elif c and not expired(c):
            state = "claimed"
        elif c:
            state = "expired"
        else:
            state = "free"
        out.append({**{k: b[k] for k in ("id", "level", "bytes", "addr")}, "count": len(fns),
                    "left": len(left), "left_bytes": sum(r["size"] for r in left), "state": state,
                    "claim": c, "finished": fin.get(b["id"])})
    return out


def functions_of(g, block_id) -> list[dict]:
    b = next((b for b in load(g)["blocks"] if b["id"] == block_id), None)
    if b is None:
        raise KeyError(f"bloc inconnu : {block_id}")
    rows = {r["name"]: r for r in g.functions()}
    port = games.portable(g)
    out = []
    for n in b["functions"]:
        r = dict(rows.get(n, {"name": n, "addr": 0, "size": 0, "done": False, "auto": "", "shared": 0, "mode": "?"}))
        if not r["done"]:
            difficulty.rate(r, port)
        out.append(r)
    return out


def claim(g, block_id=None, who=None, kind="human", level=None, note="") -> dict:
    """Takes a block (or the next free one, easiest first). Syncs with GitHub before and after."""
    who = who or config.settings()["who"]
    with _lock:
        err = gitutil.pull(g.path)
        if err:
            return {"error": f"git pull a echoue : {err}"}
        blocks = view(g)
        if block_id in (None, "", "next"):
            free = [b for b in blocks if b["state"] in ("free", "expired") and (level is None or b["level"] == int(level))]
            free.sort(key=lambda b: (b["level"], b["id"]))
            if not free:
                return {"error": "aucun bloc libre" + (f" au niveau {level}" if level is not None else "")}
            block_id = free[0]["id"]
        b = next((b for b in blocks if b["id"] == block_id), None)
        if b is None:
            return {"error": f"bloc inconnu : {block_id}"}
        if b["state"] == "claimed" and b["claim"].get("who") != who:
            return {"error": f"{block_id} est deja pris par {b['claim'].get('who')}"}
        if b["state"] == "done":
            return {"error": f"{block_id} est deja termine"}
        now = time.time()
        _write(_dir(g) / "claims" / f"{block_id}.json",
               {"block": block_id, "who": who, "kind": kind, "at": now, "touched": now, "note": note})
        err = gitutil.commit_studio(g.path, f"studio: {who} takes {block_id}")
        err = err or gitutil.push(g.path)
        if err:
            return {"error": f"bloc pris en local mais pas publie : {err}", "block": block_id}
        return {"ok": True, "block": block_id}


def touch(g, block_id, who=None, note=None) -> dict:
    """Keeps a claim alive (and optionally updates its note)."""
    p = _dir(g) / "claims" / f"{block_id}.json"
    c = _read(p, None)
    if not c:
        return {"error": "pas de claim sur ce bloc"}
    c["touched"] = time.time()
    if note is not None:
        c["note"] = note
    _write(p, c)
    gitutil.commit_studio(g.path, f"studio: {c['who']} still on {block_id}")
    return {"ok": True}


def release(g, block_id, who=None, finished_=False) -> dict:
    """Gives a block back to the queue, or closes it (finished_=True: moved to .studio/finished/)."""
    with _lock:
        gitutil.pull(g.path)
        p = _dir(g) / "claims" / f"{block_id}.json"
        c = _read(p, None)
        if not c:
            return {"error": "pas de claim sur ce bloc"}
        if who and c.get("who") != who and not expired(c):
            return {"error": f"ce bloc appartient a {c.get('who')}"}
        p.unlink()
        if finished_:
            left = next((b["left"] for b in view(g) if b["id"] == block_id), None)
            _write(_dir(g) / "finished" / f"{block_id}.json", {**c, "ended": time.time(), "left": left})
        verb = "finished" if finished_ else "released"
        err = gitutil.commit_studio(g.path, f"studio: {c['who']} {verb} {block_id}") or gitutil.push(g.path)
        return {"ok": True, "warning": err} if err else {"ok": True}


def queue_overview() -> list[dict]:
    """Every live claim of every game: who works on what."""
    out = []
    for g in games.all_games():
        if not g.ready:
            continue
        for bid, c in claims(g).items():
            out.append({"game": g.id, "title": g.title, "block": bid, **c, "expired": expired(c)})
    return sorted(out, key=lambda c: -c.get("touched", 0))
